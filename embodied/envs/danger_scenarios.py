def _as_plain_dict(config: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """Merge a Config/dict-like object with defaults without mutating it."""
    result = dict(DEFAULT_DANGER_CONFIG)
    if config:
        result.update(dict(config))
    return result


def _finite(value: Any, default: float) -> float:
    try:
        value = float(value)
    except (TypeError, ValueError):
        return default
    return value if math.isfinite(value) else default


def _replay_has_background_vehicle(
        replay_trajectory: Optional[Dict[str, Any]],
        ego_id: str = "Auto") -> bool:
    replay_trajectory = replay_trajectory or {}
    if int(replay_trajectory.get("background_vehicle_frames", 0)) > 0:
        return True
    frames = replay_trajectory.get("frames") or []
    for frame in frames:
        for snapshot in frame.get("vehicles") or []:
            if str(snapshot.get("id", "")) != ego_id:
                return True
    return False


class StructuredDangerScenarioMiner:
    """Mine failure prototypes and sample Scenario-Copy / Intent-Attack plans.

    A prototype is intentionally a compact JSON-serialisable record.  It keeps
    the source SUMO config, a critical structured state and severity signals;
    it does not depend on vehicle IDs which are often regenerated by SUMO at
    the next reset.
    """

    def __init__(
            self,
            config: Optional[Dict[str, Any]] = None,
            output_dir: str | os.PathLike[str] | None = None,
            worker_index: int = 0):
        self.config = _as_plain_dict(config)
        self.enabled = bool(self.config["enabled"])
        # Enabled means the feature is configured. Active is switched on only
        # after the bootstrap policy has completed its all-scenario evaluation.
        self.active = False
        self.record_events = False
        self.collect_episodes = bool(self.config["collect_episodes"])
        self.update_library = bool(self.config["update_library"])
        self.worker_index = int(worker_index)
        self.rng = random.Random(int(self.config["seed"]) + self.worker_index)
        self.library: list[Dict[str, Any]] = []
        self.prototype_keys: set[str] = set()
        self.episodes_seen = 0
        self.episodes_mined = 0
        self.variants_generated = 0
        self.external_prototypes_loaded = 0
        self.output_dir: Optional[Path] = Path(output_dir) if output_dir else None
        self.output_path: Optional[Path] = None
        if self.output_dir:
            self.output_path = self.output_dir / (
                f"danger_events_worker_{self.worker_index}.jsonl")

    @property
    def ready(self) -> bool:
        return (
            self.enabled and self.active and
            self.episodes_seen >= int(self.config["warmup_episodes"]) and
            bool(self.library))

    @property
    def recording(self) -> bool:
        return self.enabled and self.active and self.record_events

    @property
    def collecting(self) -> bool:
        return self.enabled and self.active and self.collect_episodes

    def set_active(
            self, active: bool,
            record_events: Optional[bool] = None,
            collect_episodes: Optional[bool] = None,
            update_library: Optional[bool] = None) -> Dict[str, float]:
        """Activate collection, event logging and online library updates.

        Each call resolves omitted collection/update flags from configuration;
        explicit overrides last until the next call. Event recording keeps the
        legacy default of following ``active``. Sweep imports remain available
        when online library updates are disabled.
        """
        if not self.enabled:
            return self.stats()
        active = bool(active)
        record_events = active if record_events is None else bool(record_events)
        if active and not self.active:
            loaded = self._load_external_prototypes()
            self.external_prototypes_loaded += loaded
            # A completed frozen-policy sweep is already the warmup library;
            # do not make post-training wait for another 20 online episodes.
            if loaded:
                self.episodes_seen = max(
                    self.episodes_seen, int(self.config["warmup_episodes"]))
        self.active = active
        self.record_events = active and record_events
        self.collect_episodes = bool(
            self.config["collect_episodes"]
            if collect_episodes is None else collect_episodes)
        self.update_library = bool(
            self.config["update_library"]
            if update_library is None else update_library)
        return self.stats()

    def record_episode(
            self,
            *,
            source_cfg: str,
            length: int,
            total_cost: float,
            max_cost: float,
            min_ttc: float,
            terminal_reason: Optional[str],
            critical_state: Optional[Iterable[float]],
            replay_trajectory: Optional[Dict[str, Any]] = None,
            generated_variant: Optional[Dict[str, Any]] = None) -> Optional[Dict[str, Any]]:
        """Log one rollout and optionally insert its failure prototype.

        Return a record only when a new online prototype entered the library.
        Independent execution-data collection uses ``collecting`` separately.
        """
        if not self.recording:
            return None
        self.episodes_seen += 1
        event_type = self._classify(max_cost, min_ttc, terminal_reason)
        record = {
            "event": "episode",
            "worker": self.worker_index,
            "episode": self.episodes_seen,
            "source_cfg": str(source_cfg),
            "length": int(length),
            "total_cost": _finite(total_cost, 0.0),
            "max_cost": _finite(max_cost, 0.0),
            "min_ttc": _finite(min_ttc, float("inf")),
            "terminal_reason": terminal_reason or "",
            "event_type": event_type or "safe",
            "generated_variant": generated_variant or {},
        }
        descriptor = self._describe_state(critical_state)
        if descriptor:
            record["critical_state"] = descriptor

        inserted = False
        if event_type:
            record["severity"] = self._severity(
                event_type, max_cost=max_cost, min_ttc=min_ttc, length=length)
            if replay_trajectory:
                record["replay_trajectory"] = replay_trajectory
            if _replay_has_background_vehicle(replay_trajectory):
                if self.update_library:
                    inserted = self._insert_prototype(record)
            else:
                record["replay_skipped_reason"] = "no_background_vehicle"
            if inserted:
                self.episodes_mined += 1
        self._write(record)
        return record if event_type and inserted else None

    def sample_variant(self, fallback_cfg: str) -> Optional[Dict[str, Any]]:
        """Return a validated *plan* for a future reset, or ``None``.

        Validating SUMO positions and applying the plan are environment-specific
        operations, so this only samples the plan.  The environment must reject
        it when the loaded initial state is already invalid.
        """
        if not self.ready:
            return None
        if not bool(self.config["generation_enabled"]):
            return None
        if self.rng.random() >= float(self.config["generate_probability"]):
            return None

        library = [
            prototype for prototype in self.library
            if _replay_has_background_vehicle(
                prototype.get("replay_trajectory"))]
        if not library:
            return None
        prototype = self._weighted_choice(library)
        replay_trajectory = prototype.get("replay_trajectory") or {}
        source_cfg = (
            prototype.get("source_cfg") or
            replay_trajectory.get("source_cfg") or
            fallback_cfg)
        if not os.path.isfile(source_cfg):
            source_cfg = fallback_cfg
        generation_mode = str(
            self.config.get("generation_mode", "mixed")).strip().lower()
        mode_aliases = {
            "scenario_copy": "copy",
            "copy_only": "copy",
            "intent_attack": "attack",
            "attack_only": "attack",
            "replay_only": "replay",
            "none": "off",
            "disabled": "off",
            "false": "off",
        }
        generation_mode = mode_aliases.get(generation_mode, generation_mode)
        if generation_mode in ("off", "normal"):
            return None
        if generation_mode == "copy":
            mode = "scenario_copy"
            kind = "scenario_copy"
        elif generation_mode == "attack":
            mode = "intent_attack"
            kind = "intent_attack"
        elif generation_mode == "replay":
            mode = "replay"
            kind = "replay"
        elif generation_mode == "mixed":
            replay_probability = float(self.config.get(
                "replay_probability", 1.0 / 3.0))
            replay_probability = max(0.0, min(1.0, replay_probability))
            if self.rng.random() < replay_probability:
                mode = "replay"
                kind = "replay"
            else:
                mode = (
                    "intent_attack"
                    if self.rng.random() < float(self.config["intent_attack_probability"])
                    else "scenario_copy")
                kind = mode
        else:
            mode = (
                "intent_attack"
                if self.rng.random() < float(self.config["intent_attack_probability"])
                else "scenario_copy")
            kind = mode
        variant = {
            "event": "variant",
            "worker": self.worker_index,
            "mode": mode,
            "kind": kind,
            "source_cfg": str(source_cfg),
            "prototype_type": prototype["event_type"],
            "prototype_severity": float(prototype["severity"]),
            "copy_speed_jitter": self.rng.uniform(
                -float(self.config["copy_speed_jitter"]),
                float(self.config["copy_speed_jitter"])),
            "attack_speed_delta": self.rng.uniform(
                0.5 * float(self.config["attack_speed_delta"]),
                float(self.config["attack_speed_delta"])),
        }
        if "critical_state" in prototype:
            variant["prototype_state"] = prototype["critical_state"]
        if replay_trajectory:
            variant["replay_trajectory"] = replay_trajectory
        self.variants_generated += 1
        if self.record_events:
            self._write(variant)
        return variant

    def stats(self) -> Dict[str, float]:
        return {
            "episodes_seen": float(self.episodes_seen),
            "episodes_mined": float(self.episodes_mined),
            "library_size": float(len(self.library)),
            "variants_generated": float(self.variants_generated),
            "external_prototypes_loaded": float(self.external_prototypes_loaded),
            "record_events": float(self.record_events),
            "collect_episodes": float(self.collect_episodes),
            "update_library": float(self.update_library),
        }

    def _classify(
            self, max_cost: float, min_ttc: float,
            terminal_reason: Optional[str]) -> Optional[str]:
        if not self.recording:
            return None
        if terminal_reason == "collision":
            return "collision"
        if terminal_reason in ("max_time", "max_steps", "sumo_closed"):
            return "low_progress"
        if _finite(min_ttc, float("inf")) < float(self.config["near_miss_ttc"]):
            return "near_miss"
        if _finite(max_cost, 0.0) >= float(self.config["risk_cost_threshold"]):
            return "high_risk_cost"
        return None

    def _severity(
            self, event_type: str, *, max_cost: float,
            min_ttc: float, length: int) -> float:
        ttc = _finite(min_ttc, float("inf"))
        risk = max(0.0, _finite(max_cost, 0.0))
        threshold = max(float(self.config["near_miss_ttc"]), 1e-6)
        ttc_pressure = max(0.0, (threshold - ttc) / threshold) if math.isfinite(ttc) else 0.0
        base = {
            "collision": 10.0,
            "near_miss": 4.0,
            "high_risk_cost": 3.0,
            "low_progress": 1.0,
        }[event_type]
        # A shorter collision is generally harder than a late collision.
        early_failure = max(0.0, (200.0 - min(max(length, 0), 200)) / 200.0)
        return base + 2.0 * min(risk, 1.0) + 2.0 * ttc_pressure + early_failure

    def _prototype_key(self, prototype: Dict[str, Any]) -> str:
        identity = {
            "source_cfg": prototype.get("source_cfg", ""),
            "worker": prototype.get("worker", ""),
            "episode": prototype.get("episode", ""),
            "event_type": prototype.get("event_type", ""),
            "terminal_reason": prototype.get("terminal_reason", ""),
            "length": prototype.get("length", ""),
            "critical_state": prototype.get("critical_state", {}),
        }
        payload = json.dumps(
            self._json_safe(identity),
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"))
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()

    def _insert_prototype(self, prototype: Dict[str, Any]) -> bool:
        key = self._prototype_key(prototype)
        if key in self.prototype_keys:
            return False
        capacity = max(1, int(self.config["library_size"]))
        if len(self.library) < capacity:
            self.library.append(prototype)
            self.prototype_keys.add(key)
            return True
        weakest_index = min(
            range(len(self.library)), key=lambda index: self.library[index]["severity"])
        if prototype["severity"] > self.library[weakest_index]["severity"]:
            old_key = self._prototype_key(self.library[weakest_index])
            self.prototype_keys.discard(old_key)
            self.library[weakest_index] = prototype
            self.prototype_keys.add(key)
            return True
        return False

    def _weighted_choice(self, records: list[Dict[str, Any]]) -> Dict[str, Any]:
        weights = [max(1e-3, float(record["severity"])) for record in records]
        return self.rng.choices(records, weights=weights, k=1)[0]

    def _describe_state(self, state: Optional[Iterable[float]]) -> Dict[str, Any]:
        if state is None:
            return {}
        values = np.asarray(state, dtype=np.float32).reshape(-1)
        # Current SUMO state: ego speed + six [x, y, vx, vy, heading] slots.
        if values.size < 6:
            return {"raw": values.tolist()}
        closest = None
        for index in range(6):
            start = 1 + 5 * index
            if start + 5 > values.size:
                break
            rel_x, rel_y, rel_vx, rel_vy, heading = values[start:start + 5]
            # Empty slots use a very large normalized position in sumo_merge.py.
            distance = float(np.hypot(rel_x, rel_y))
            if distance > 1.2:
                continue
            candidate = {
                "slot": index,
                "rel_x_norm": float(rel_x),
                "rel_y_norm": float(rel_y),
                "rel_vx_norm": float(rel_vx),
                "rel_vy_norm": float(rel_vy),
                "heading_norm": float(heading),
                "distance_norm": distance,
            }
            if closest is None or distance < closest["distance_norm"]:
                closest = candidate
        return {
            "ego_speed_norm": float(values[0]),
            "closest_agent": closest or {},
        }

    def _write(self, record: Dict[str, Any]) -> None:
        if not self.output_path:
            return
        self.output_path.parent.mkdir(parents=True, exist_ok=True)
        safe_record = self._json_safe(record)
        with self.output_path.open("a", encoding="utf-8") as file:
            file.write(json.dumps(safe_record, ensure_ascii=False, sort_keys=True))
            file.write("\n")

    def _load_external_prototypes(self) -> int:
        """Import rare cases emitted by the frozen-policy all-scene sweep."""
        if not self.output_dir or not self.output_dir.exists():
            return 0
        loaded = 0
        for path in self.output_dir.glob("danger_events_worker_*.jsonl"):
            try:
                lines = path.read_text(encoding="utf-8").splitlines()
            except OSError:
                continue
            for line in lines:
                try:
                    record = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if (
                        record.get("event") != "episode" or
                        record.get("event_type") in (None, "safe") or
                        "severity" not in record):
                    continue
                if self._insert_prototype(record):
                    loaded += 1
        return loaded

    def _json_safe(self, value: Any) -> Any:
        if isinstance(value, dict):
            return {str(k): self._json_safe(v) for k, v in value.items()}
        if isinstance(value, (list, tuple)):
            return [self._json_safe(v) for v in value]
        if isinstance(value, (float, np.floating)):
            return float(value) if math.isfinite(float(value)) else None
        if isinstance(value, (np.integer,)):
            return int(value)
        return value
