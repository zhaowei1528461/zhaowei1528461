"""Online hard-scenario mining for structured driving observations.

The SUMO environment exposes a compact state vector instead of a scene graph or
images.  This module keeps the World Engine feedback loop in that setting:

1. Record the situations in which the *current* policy collides, gets close to
   a collision, or makes no route progress.
2. Retain a bounded library of the most severe episode prototypes.
3. Resample a source scenario and produce a small traffic-intent perturbation
   for a later reset.

The actual SUMO API calls deliberately stay in ``sumo_merge.py``.  Keeping the
miner pure Python makes the mining policy easy to unit test and also keeps it
usable with another structured-data driving backend.
"""

from __future__ import annotations

import json
import hashlib
import math
import os
import random
from pathlib import Path
from typing import Any, Dict, Iterable, Optional

import numpy as np


